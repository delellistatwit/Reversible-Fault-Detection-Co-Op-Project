"""Exhaustive experiments: correct and faulty simulations for every circuit in a configuration file.

For each circuit, every valid fault is simulated on every input. Three files are
written per circuit, all named by the run ID (RUN_<circuit>_<date>):

    results/raw/<run_id>.csv      one row per fault and input: correct output, faulty output, detected (1/0)
    results/matrix/<run_id>.csv   one row per fault, one column per input, 1 = detected
    results/logs/<run_id>.txt     run ID, counts, runtime, and consistency checks

Bit strings list wire 0 first. Outputs are generated by this script only and are never edited by hand.

Run from the repository root:
    python -m src.experiment                        (uses configs/week5.json)
    python -m src.experiment configs/week5.json
"""

import csv
import json
import os
import subprocess
import sys
import time
from datetime import date

from src.faults import FaultGenerator, classify_faults, INVALID
from src.fault_catalog import build_catalog

DEFAULT_CONFIG = "configs/week5.json"


def bits(vector):
    """Turn (1, 0, 1) into "101"."""
    return "".join(str(b) for b in vector)


def load_config(path, circuits):
    """Read a configuration file and check that every circuit name exists."""
    with open(path, "r") as file:
        config = json.load(file)

    unknown = [c for c in config["circuits"] if c not in circuits]
    if unknown:
        raise ValueError(f"{path}: unknown circuits {unknown}")
    return config


def git_commit():
    """Return the short ID of the current commit, or "unknown" if git is not available."""
    try:
        return subprocess.run(["git", "rev-parse", "--short", "HEAD"],
                              capture_output=True, text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def simulate_circuit(circuit):
    """Simulate the correct circuit and every valid fault on every input.

    Returns (inputs, raw_rows, matrix) where raw_rows has one entry per fault and input,
    and matrix maps each fault ID to a list of 1/0 detection values (one per input).
    """
    correct = circuit.truth_table()
    inputs = [v for v, _ in correct]
    raw_rows = []
    matrix = {}

    for fault, status, _ in classify_faults(circuit, FaultGenerator(circuit).generate_all()):
        if status == INVALID:
            continue                                   # invalid faults have no circuit to simulate
        faulty = fault.apply(circuit).truth_table()
        row = []
        for (v, good), (_, bad) in zip(correct, faulty):
            detected = int(good != bad)
            row.append(detected)
            raw_rows.append({
                "fault_id": fault.get_id(),
                "status": status,
                "input": bits(v),
                "correct_output": bits(good),
                "faulty_output": bits(bad),
                "detected": detected,
            })
        matrix[fault.get_id()] = row

    return inputs, raw_rows, matrix


def check_results(circuit_id, circuit, inputs, raw_rows, matrix):
    """Consistency checks: sizes of the raw and matrix data, and agreement with the fault catalog."""
    catalog = {r["fault_id"]: r["detected_count"] for r in build_catalog(circuit_id, circuit)
               if r["status"] != INVALID}
    return {
        "inputs = 2^wires": len(inputs) == 2 ** circuit.num_wires,
        "raw rows = faults x inputs": len(raw_rows) == len(matrix) * len(inputs),
        "every matrix row has one value per input": all(len(row) == len(inputs) for row in matrix.values()),
        "matrix agrees with fault catalog": {f: sum(row) for f, row in matrix.items()} == catalog,
    }


def write_csv(path, header, rows):
    with open(path, "w", newline="") as file:
        writer = csv.writer(file)
        writer.writerow(header)
        writer.writerows(rows)


def run_circuit(experiment, circuit_id, circuit, run_date, commit):
    """Run one circuit and write its raw results, matrix, and log. Returns the run ID."""
    run_id = f"RUN_{circuit_id}_{run_date}"
    start = time.perf_counter()
    inputs, raw_rows, matrix = simulate_circuit(circuit)
    runtime = time.perf_counter() - start
    checks = check_results(circuit_id, circuit, inputs, raw_rows, matrix)

    raw_header = ["run_id", "circuit_id", "fault_id", "status", "input", "correct_output", "faulty_output", "detected"]
    write_csv(f"results/raw/{run_id}.csv", raw_header,
              [[run_id, circuit_id] + [r[k] for k in raw_header[2:]] for r in raw_rows])

    write_csv(f"results/matrix/{run_id}.csv", ["fault_id"] + [bits(v) for v in inputs],
              [[fault_id] + row for fault_id, row in matrix.items()])

    undetectable = [f for f, row in matrix.items() if sum(row) == 0]
    lines = [
        f"run_id: {run_id}",
        f"experiment: {experiment}",
        f"circuit: {circuit_id}",
        f"date: {run_date}",
        f"commit: {commit}",
        f"wires: {circuit.num_wires}",
        f"gates: {len(circuit.gates)}",
        f"inputs: {len(inputs)}",
        f"faults simulated: {len(matrix)}",
        f"raw rows: {len(raw_rows)}",
        f"undetectable faults: {len(undetectable)} {undetectable}",
        f"simulation time (s): {runtime:.4f}",
        "checks:",
    ] + [f"  {'PASS' if ok else 'FAIL'}  {name}" for name, ok in checks.items()]
    with open(f"results/logs/{run_id}.txt", "w") as file:
        file.write("\n".join(lines) + "\n")

    status = "PASS" if all(checks.values()) else "FAIL"
    print(f"  {run_id:38} {len(matrix):4} faults x {len(inputs):3} inputs  {runtime:7.4f} s  checks {status}")
    return run_id


def main():
    from src.integrated_run import CIRCUITS

    path = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_CONFIG
    config = load_config(path, CIRCUITS)
    for folder in ("results/raw", "results/matrix", "results/logs"):
        os.makedirs(folder, exist_ok=True)

    run_date = date.today().isoformat()
    commit = git_commit()
    print(f"\nExperiment {config['experiment']} ({path}), commit {commit}")
    for circuit_id in config["circuits"]:
        run_circuit(config["experiment"], circuit_id, CIRCUITS[circuit_id](), run_date, commit)


if __name__ == "__main__":
    main()